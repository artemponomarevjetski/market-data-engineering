-- QUERY 1
SELECT		G.ID 
	,	G.SECCODE
	,	G.NAME
	,	D.DIVTYPECODE
	,	DT.DESC_ AS DIVTYPEDESC
	,	D.EFFECTIVEDATE
	,	D.RECORDDATE
	,	D.PAYDATE
	,	D.DIVRATE
	,	D.TAXMARKER -- 'N' = NET;  'G' = GROSS
	,	D.ISOCURRCODE
	,	d.infocode
FROM		GSECMSTRX G
JOIN		GSECMAPX M
	ON	M.SECCODE = G.SECCODE
	AND	M.VENTYPE = 33
JOIN		DS2DIV D
	ON	D.INFOCODE = M.VENCODE
JOIN		DS2XREF DT
	ON	DT.CODE = D.DIVTYPECODE
	AND	DT.TYPE_ = 8

WHERE		G.ID = '@TOYOT17'
ORDER BY EFFECTIVEDATE DESC


SELECT
X.ID
, X.NAME
, I.INFOCODE
, I.DSQTNAME
, I.DSMNEM
, I.TYPECODE
FROM SECMSTRX X
JOIN SECMAPX M
ON X.SECCODE = M.SECCODE
AND X.TYPE_ = 1
AND M.VENTYPE = 33 -- DATASTREAM ONLY
JOIN DS2CTRYQTINFO I
ON I.INFOCODE = M.VENCODE -- JOIN ON INFOCODE
WHERE
X.ID = 'MSFT' -- MICROSOFT

