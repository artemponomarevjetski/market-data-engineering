--FROM ID TO DATASTREAM AND WORLDSCOPE
SELECT X.ID, X.SECCODE, X.NAME, DI.INFOCODE, DI.DSQTNAME, W.VENCODE as WORLDSCOPE_CODE, WI.NAME, W.ISRCODE
FROM VW_SECURITYMASTERX X

JOIN VW_DS2MAPPING D
ON X.SECCODE = D.SECCODE
AND D.TYP = X.TYP

JOIN DS2CTRYQTINFO DI
ON DI.INFOCODE = D.VENCODE

LEFT JOIN VW_WSCOMPANYMAPPING W -- if no direct mapping exists, primary issue of company is used
ON X.SECCODE = W.seccode
AND W.typ = X.typ

LEFT JOIN WSINFO WI
ON W.VENCODE = WI.CODE

WHERE X.ID IN ('HMC', '@HONDA9')


-- QUERY 2 -- QAID, DATASTREAM and MSCI V2 (via Time Series Mapping) 

SELECT	MR.ID
,		MR.NAME
,		V.INFOCODE -- DATASTREAM VENCODE
,		V.MARKETDATE
,		V.CLOSE_
,		O.SECID		-- MSCI V2 VENCODE
,		O.NAME_ AS MSCI_NAME
FROM	GSECMSTRX MR

JOIN	GSECMAPX MP
	ON	MP.SECCODE = MR.SECCODE
	AND MP.VENTYPE = 33 --DS2 PRICING

JOIN	DS2PRIMQTPRC V
	ON	V.INFOCODE = MP.VENCODE

JOIN	GSECMAPX MP2
	ON	MP2.SECCODE = MP.SECCODE
	AND MP2.VENTYPE = 48  --MSCIV2
	AND V.MARKETDATE BETWEEN MP2.STARTDATE AND MP2.ENDDATE  -- FOR EACH PRICING DATE, FIND THE MSCI VENCODE

JOIN	MS2SECINFO O
	ON	O.SECID = MP2.VENCODE

WHERE MR.ID = '@BALLA2'
ORDER BY V.MARKETDATE