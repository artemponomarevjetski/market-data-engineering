-- QUERY 1 -- MAIN DATASTREAM TABLES
SELECT		G.ID
	,	G.SEDOL
	,	G.NAME
	,	X.INFOCODE								-- DATASTREAM VENCODE
	,	R.DESC_ AS SECURITY_TYPE
	,	P.MARKETDATE
	,	EX.EXCHNAME								AS EXCHANGE
	,	X.ISPRIMEXCHQT							
	,	P.ISOCURRCODE							
	,	A.CUMADJFACTOR							AS ADJUSTMENT_FACTOR
	,	P.CLOSE_								AS CLOSE_UNADJUSTED_LOC
	,	P.CLOSE_ * A.CUMADJFACTOR				AS CLOSE_ADJUSTED_LOC
	, M.vencode
FROM		SECMSTRX G
JOIN		SECMAPX M
	ON	M.SECCODE = G.SECCODE
	AND	M.VENTYPE = 33							-- DATASTREAM
JOIN		DS2CTRYQTINFO I
	ON	I.INFOCODE = M.VENCODE
JOIN	DS2XREF R
	ON	I.TYPECODE = R.CODE
	AND R.TYPE_ = 2								-- SECURITY TYPE DESCRIPTIONS
JOIN		DS2EXCHQTINFO X						-- LIST OF EXCHANGES PER INFOCODE 
	ON	X.INFOCODE = M.VENCODE
JOIN		DS2EXCHANGE EX
	ON	EX.EXCHINTCODE = X.EXCHINTCODE
JOIN		(SELECT * FROM DS2PRIMQTPRC UNION SELECT * FROM DS2SCDQTPRC) P  -- PRICING FOR ALL EXCHANGES
	ON	P.INFOCODE = X.INFOCODE
	AND	P.EXCHINTCODE = X.EXCHINTCODE
JOIN		DS2ADJ A							-- TO ADJUST VALUES
	ON	A.INFOCODE = M.VENCODE
	AND	P.MARKETDATE BETWEEN A.ADJDATE AND ISNULL(A.ENDADJDATE, '21000101')
	AND	A.ADJTYPE = 2
WHERE		G.ID = 'AAPL' AND P.MARKETDATE >  '1/1/2006' 
	ORDER BY	G.ID
	,	P.MARKETDATE DESC
	,	EX.EXCHNAME
	

-- QUERY 2 -- VIEWS

DECLARE @QAID VARCHAR(MAX) = '@DEUTS65' --INSERT THE QAID
DECLARE @ADJUSTMENT INT = 2 -- 0 = NO ADJUSTMENT, 1 = SPLIT ADJUSTED, 2 = ADJUSTED FOR ALL CORPORATE EVENTS

SELECT      @QAID AS QAID,
            MS.NAME,
            P.INFOCODE,
            P.DSCODE,
            P.EXCHINTCODE AS EXCHANGENUM,
            P.EXCHNAME, 
            P.ISPRIMEXCHQT, 
            P.MARKETDATE, 
            P.CURRENCY,
            P.CLOSE_ AS CLOSEPRICE_LOC, 
            P.CLOSE_ / X.MIDRATE AS CLOSEPRICE_USD,
            P.VOLUME,
--          P.CONSOLVOL,
            P.ADJTYPE,
            P.CUMADJFACTOR,
            MP.RANK
FROM VW_SECURITYMASTERX MS
JOIN VW_DS2MAPPING MP
            ON MS.SECCODE = MP.SECCODE
			AND MS.TYP = MP.TYP
			AND MS.ID = @QAID

JOIN VW_DS2PRICING P
            ON    P.INFOCODE = MP.VENCODE
            
LEFT JOIN VW_DS2FXCROSS X
	ON P.CURRENCY = X.FROMCURRCODE
	AND X.TOCURRCODE = 'USD'
	AND P.MARKETDATE = X.EXRATEDATE
	AND X.RATETYPE = 'SPOT'
	
WHERE MS.ID = @QAID AND  P.ADJTYPE = @ADJUSTMENT AND P.CLOSE_ IS NOT NULL 
ORDER BY P.INFOCODE DESC, P.MARKETDATE DESC
 